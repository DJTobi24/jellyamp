// swift-tools-version:5.9
import PackageDescription

// The in-app demo backend: a fictional music library and just enough of the
// Jellyfin REST API (and of the Sonic API) to serve it, plus a loopback HTTP
// server. The app signs in to it in demo mode (App Review, UI tests,
// screenshots) exactly like to a real server, so no screen knows about demo
// mode. Everything here builds and is tested on Linux — the tests drive the
// real API clients of JellyfinBackend and SonicClient against it.
let package = Package(
    name: "JellyfinDemo",
    platforms: [.iOS(.v16), .macOS(.v13)],
    products: [
        .library(name: "JellyfinDemo", targets: ["JellyfinDemo"])
    ],
    dependencies: [
        .package(path: "../JellyampCore"),
        .package(path: "../JellyfinBackend"),
        .package(path: "../SonicClient"),
    ],
    targets: [
        .target(
            name: "JellyfinDemo",
            dependencies: ["JellyampCore"],
            // Generated by scripts/demo-audio/make.py (synthesized, nobody's
            // recording).
            resources: [.copy("Resources/Loops")]
        ),
        .testTarget(
            name: "JellyfinDemoTests",
            dependencies: ["JellyfinDemo", "JellyfinBackend", "SonicClient"]
        ),
    ]
)
